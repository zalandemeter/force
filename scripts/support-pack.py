#!/usr/bin/env python3
"""Write the generated part of Chuck's context pack (SPEC §50) from the repository, into a release's
share/support/ (scripts/build-release.sh and deploy.sh run it; in the checkout the files are git-ignored):

  docs.md          the website's docs page as Markdown (website/tools/md.py, as the website's docs.md)
  commands.md      `force --help` and every subcommand's help
  contributing.md  CONTRIBUTING.md

  scripts/support-pack.py [--out DIR]   write them (default: share/support in this checkout)

CHUCK.md, faq.md and architecture.md are written by hand.
"""
from __future__ import annotations

import argparse
import contextlib
import io
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "share" / "support"
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "website" / "tools"))

HEADER = "<!-- generated by scripts/support-pack.py from {src}: do not edit -->\n\n"


def docs_md() -> str:
    import build      # website/tools/build.py: repo_links
    from md import html_to_md
    html = build.repo_links((REPO / "website" / "docs.html").read_text(encoding="utf-8"))
    return HEADER.format(src="website/docs.html") + html_to_md(html, "docs.html")


def _help(parser) -> str:
    parser.prog = "force"
    with contextlib.redirect_stdout(io.StringIO()) as out:
        parser.print_help()
    return out.getvalue().rstrip()


def commands_md() -> str:
    import argparse as ap
    import os
    os.environ["COLUMNS"] = "110"         # stable wrapping, whatever the terminal
    from force.cli import build_parser
    root = build_parser()
    parts = [HEADER.format(src="force/cli.py") + "# Force commands\n\nEvery `force` command with its options, "
             "from `force --help` and `force COMMAND --help`.\n\n```text\n" + _help(root) + "\n```"]
    for a in root._actions:
        if isinstance(a, ap._SubParsersAction):
            for name, sp in a.choices.items():
                sp.prog = f"force {name}"
                parts.append(f"## force {name}\n\n```text\n{_help(sp)}\n```")
                for b in sp._actions:
                    if isinstance(b, ap._SubParsersAction):
                        for n2, s2 in b.choices.items():
                            s2.prog = f"force {name} {n2}"
                            parts.append(f"### force {name} {n2}\n\n```text\n{_help(s2)}\n```")
    return "\n\n".join(parts) + "\n"


def contributing_md() -> str:
    return HEADER.format(src="CONTRIBUTING.md") + (REPO / "CONTRIBUTING.md").read_text(encoding="utf-8")


FILES = {"docs.md": docs_md, "commands.md": commands_md, "contributing.md": contributing_md}


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--out", type=Path, default=OUT, help="where to write them (default: share/support)")
    args = p.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    for name, make in FILES.items():
        (args.out / name).write_text(make(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
